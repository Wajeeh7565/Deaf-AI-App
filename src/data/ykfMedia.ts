export const getKioskPhoto = (airline: string): YkfPhoto => {
  if (airline.includes('WestJet')) return YKF_MEDIA.kioskWestJet;
  if (airline.includes('Flair')) return YKF_MEDIA.kioskFlair;
  return YKF_MEDIA.kioskAll;
};

export const getBagDropPhoto = (airline: string): YkfPhoto => {
  if (airline.includes('WestJet')) return YKF_MEDIA.bagDropWestJet;
  if (airline.includes('Flair')) return YKF_MEDIA.bagDropFlair;
  return YKF_MEDIA.bagDropAll;
};

export const getGatePhoto = (airline: string): YkfPhoto => {
  if (airline.includes('WestJet')) return YKF_MEDIA.gateWestJet;
  if (airline.includes('Flair')) return YKF_MEDIA.gateFlair;
  return YKF_MEDIA.gateEntrance;
};

// Passenger-facing guidance only. The close-up self-bag-drop photos are kept in
// the media library for internal reference but are intentionally not shown here,
// because YKF advised that at least one baggage image represented a non-public area.
export const getBagDropGallery = (airline: string): YkfPhoto[] => [
  getKioskPhoto(airline),
  YKF_MEDIA.checkinArea,
  YKF_MEDIA.checkinCounters,
  YKF_MEDIA.lobbyQueuesFront,
];

export const getGateGallery = (airline: string): YkfPhoto[] => [
  YKF_MEDIA.gateEntrance,
  getGatePhoto(airline),
];

